export function metrics(apps:Application[], now=Date.now()) {
 const responses=apps.filter(a=>['Screening','Interview','Offer','Rejected'].includes(a.status)).length;
 const submitted=apps.filter(a=>['Applied','Screening','Interview','Offer','Rejected'].includes(a.status)).length;
 return {total:apps.length,upcoming:apps.flatMap(a=>a.interviews).filter(i=>i.status==='Scheduled'&&Date.parse(i.at)>=now).length,offers:apps.filter(a=>a.status==='Offer').length,response:submitted?responses/submitted*100:0};
}
export function validateDraft(d:Draft) {
 const errors:Record<string,string>={};
 if(!d.company.trim())errors.company='Nhập tên công ty.';
 else if(d.company.trim().length>250)errors.company='Tên công ty không được vượt quá 250 ký tự.';
 if(!d.position.trim())errors.position='Nhập vị trí ứng tuyển.';
 else if(d.position.trim().length>250)errors.position='Vị trí ứng tuyển không được vượt quá 250 ký tự.';
 if(d.source&&d.source.trim().length>128)errors.source='Nguồn tuyển dụng không được vượt quá 128 ký tự.';
 if(d.jobCode&&d.jobCode.trim().length>128)errors.jobCode='Mã tin tuyển dụng không được vượt quá 128 ký tự.';
 if(d.location&&d.location.trim().length>250)errors.location='Địa điểm không được vượt quá 250 ký tự.';
 if(d.salary&&d.salary.trim().length>250)errors.salary='Lương tham khảo không được vượt quá 250 ký tự.';
 if(d.notes&&d.notes.length>5000)errors.notes='Ghi chú không được vượt quá 5000 ký tự.';
 if(d.nextAction&&d.nextAction.length>250)errors.nextAction='Hành động tiếp theo không được vượt quá 250 ký tự.';
 if(d.url){
   if(d.url.length>2000)errors.url='URL tin tuyển dụng không được vượt quá 2000 ký tự.';
   else {
     try{if(!['http:','https:'].includes(new URL(d.url).protocol))throw Error();}catch{errors.url='Dùng địa chỉ http hoặc https hợp lệ.';}
   }
 }
 if(d.deadline&&!Number.isFinite(Date.parse(d.deadline)))errors.deadline='Chọn ngày và giờ hợp lệ.';
 if(d.deadline&&!d.nextAction.trim())errors.nextAction='Nhập hành động hoặc xóa deadline.';
 return errors;
}
export function normalizedUrl(input:string){
 if(!input)return ''; let url:URL;try{url=new URL(input);}catch{return '';}if(!['http:','https:'].includes(url.protocol))return '';url.hash='';for(const key of [...url.searchParams.keys()])if(key.startsWith('utm_')||['fbclid','gclid'].includes(key))url.searchParams.delete(key);url.searchParams.sort();return url.toString();
}
export function duplicate(apps:Application[],draft:Draft,exclude=''){
 const identity=(value:string)=>value.trim().normalize('NFKC').toLocaleLowerCase('und');
 const matches=apps.filter(a=>a.id!==exclude&&((draft.source.trim()&&draft.jobCode.trim()&&identity(a.source)===identity(draft.source)&&identity(a.jobCode)===identity(draft.jobCode))||(draft.url&&a.url&&normalizedUrl(draft.url)&&normalizedUrl(draft.url)===normalizedUrl(a.url))));
 return matches.find(a=>!['Rejected','Withdrawn'].includes(a.status))||matches[0];
}
export function actionable(apps:Application[]){return apps.filter(a=>a.nextAction.trim()).sort((a,b)=>(a.deadline||'z').localeCompare(b.deadline||'z')||a.createdAt.localeCompare(b.createdAt)||a.id.localeCompare(b.id));}
export function filtered(apps:Application[],query:string,status:string,sort:string,priority?:string,tag?:string){
 const term=query.trim().toLocaleLowerCase('vi'); const cleanTag=tag?tag.trim().toLowerCase().replace(/^#/,''):'';
 return apps.filter(a=>(!term||`${a.company} ${a.position}`.toLocaleLowerCase('vi').includes(term))&&(status==='all'||a.status===status)&&(!priority||priority==='all'||(a.priority||'target')===priority)&&(!cleanTag||(Array.isArray(a.tags)&&a.tags.some(t=>t.toLowerCase().includes(cleanTag))))).sort((a,b)=>{const key=sort.startsWith('applied')?'appliedAt':'createdAt';const sign=sort.endsWith('asc')?1:-1;if(!a[key])return b[key]?1:0;if(!b[key])return -1;return a[key].localeCompare(b[key])*sign;});
}
